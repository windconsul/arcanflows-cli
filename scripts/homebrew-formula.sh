#!/usr/bin/env bash
# Write Formula/arcanflows.rb for a released version from its checksums.txt.
#
#   scripts/homebrew-formula.sh 0.10.0 dist/checksums.txt > Formula/arcanflows.rb
#
# The release workflow runs this after every tag, so the formula always points
# at the newest release of this public repo with real SHA-256 sums.
set -euo pipefail
VERSION="${1#v}"; SUMS="$2"
REPO="${ARCANFLOWS_CLI_REPO:-windconsul/arcanflows-cli}"
sum() {
  local s
  s=$(awk -v f="$1" '$2 == f || $2 == "*"f { print $1 }' "$SUMS")
  [[ "$s" =~ ^[0-9a-f]{64}$ ]] || { echo "no SHA-256 for $1 in $SUMS" >&2; exit 1; }
  echo "$s"
}
cat <<RUBY
# Homebrew formula for the ArcanFlows CLI — generated by scripts/homebrew-formula.sh
# for v${VERSION}; do not edit by hand.
#
#   brew tap windconsul/arcanflows-cli https://github.com/${REPO}
#   brew install windconsul/arcanflows-cli/arcanflows
#   brew upgrade arcanflows

class Arcanflows < Formula
  desc "ArcanFlows CLI - AI Automation from your terminal"
  homepage "https://arcanflows.com"
  version "${VERSION}"
  license :cannot_represent

  on_macos do
    if Hardware::CPU.arm?
      url "https://github.com/${REPO}/releases/download/v#{version}/arcanflows-darwin-arm64"
      sha256 "$(sum arcanflows-darwin-arm64)"
    else
      url "https://github.com/${REPO}/releases/download/v#{version}/arcanflows-darwin-amd64"
      sha256 "$(sum arcanflows-darwin-amd64)"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "https://github.com/${REPO}/releases/download/v#{version}/arcanflows-linux-arm64"
      sha256 "$(sum arcanflows-linux-arm64)"
    else
      url "https://github.com/${REPO}/releases/download/v#{version}/arcanflows-linux-amd64"
      sha256 "$(sum arcanflows-linux-amd64)"
    end
  end

  def install
    os = OS.mac? ? "darwin" : "linux"
    arch = Hardware::CPU.arm? ? "arm64" : "amd64"
    bin.install "arcanflows-#{os}-#{arch}" => "arcanflows"
    generate_completions_from_executable(bin/"arcanflows", "completion")
  end

  test do
    assert_match "ArcanFlows CLI #{version}", shell_output("#{bin}/arcanflows version")
  end
end
RUBY
